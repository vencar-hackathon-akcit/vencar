from datetime import datetime
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field
from pydantic.alias_generators import to_camel


class DomainModel(BaseModel):
    """Base model that accepts snake_case in code and exposes camelCase externally."""

    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True)


class Category(StrEnum):
    """Evaluation categories that compose the Vencar score."""

    STRUCTURAL = "structural"
    MECHANICAL = "mechanical"
    ELECTRICAL = "electrical"
    AESTHETIC = "aesthetic"
    DOCUMENTATION = "documentation"


class Severity(StrEnum):
    """How serious an observed damage is."""

    MINOR = "minor"
    MODERATE = "moderate"
    SEVERE = "severe"


class Confidence(StrEnum):
    """How sure an agent is about a finding."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class AssessmentStatus(StrEnum):
    """Lifecycle states of an assessment."""

    PROCESSING = "processing"
    COMPLETED = "completed"
    NEEDS_INPUT = "needs_input"
    INCONCLUSIVE = "inconclusive"
    FAILED = "failed"


class ScoreBand(StrEnum):
    """Bands of the Vencar score scale."""

    ATTENTION = "attention"
    REGULAR = "regular"
    VERY_GOOD = "very_good"


class AssessmentStage(StrEnum):
    """Stages of an agent run, as shown to the user."""

    RECEIVED = "received"
    ANALYZING = "analyzing"
    VALIDATING = "validating"
    FINISHED = "finished"


class EventKind(StrEnum):
    """Kinds of entries in an assessment's history."""

    STEP = "step"
    TOOL = "tool"
    DECISION = "decision"
    USER_INPUT = "user_input"


class EventName(StrEnum):
    """Names of the history entries that are not tool calls."""

    RECEIVED = "received"
    MISSING_DATA_REQUESTED = "missing_data_requested"
    ORCHESTRATOR = "orchestrator"
    VALIDATED = "validated"
    DOSSIER_ISSUED = "dossier_issued"
    FAILED = "failed"
    USER_ANSWER = "user_answer"


class SpecialistName(StrEnum):
    """Specialist agents available to the orchestrator."""

    BODYWORK = "agente_funilaria"
    INTERIOR = "agente_tapecaria"


class VehicleMatchStatus(StrEnum):
    """Whether the photos agree with the vehicle the user informed."""

    MATCHES = "matches"
    MISMATCH = "mismatch"
    CANNOT_DETERMINE = "cannot_determine"


class VehicleData(DomainModel):
    """Vehicle data informed by the user."""

    make: str = ""
    model: str = ""
    year: str = ""
    plate: str = ""
    mileage: str = ""
    region: str = ""
    usage: str = ""

    def missing_required(self) -> list[str]:
        """Return the required vehicle fields that are empty."""
        return [
            name for name in ("make", "model", "year", "plate") if not getattr(self, name).strip()
        ]


class Photo(DomainModel):
    """Stored photo used as evidence."""

    id: str
    evidence_id: str
    filename: str
    path: str = Field(exclude=True)


class Evidence(DomainModel):
    """Piece of evidence received for an assessment."""

    id: str
    kind: str
    content: str
    photo_id: str | None = None


class PhotoAssessment(DomainModel):
    """Verdict about whether a photo can support an analysis."""

    evidence_id: str
    usable: bool
    reason: str


class Damage(DomainModel):
    """Damage directly observed in a photo."""

    evidence_id: str
    location: str
    damage_type: str
    severity: Severity
    category: Category
    confidence: Confidence
    observation: str


class Hypothesis(DomainModel):
    """Interpretation generated by an agent, kept apart from observed evidence."""

    description: str
    confidence: Confidence
    evidence_ids: list[str]
    what_would_confirm: str


class ConflictTopic(StrEnum):
    """What a conflict is about."""

    VEHICLE_IDENTITY = "vehicle_identity"
    OTHER = "other"


class Conflict(DomainModel):
    """Disagreement between pieces of evidence."""

    topic: ConflictTopic = ConflictTopic.OTHER
    description: str
    evidence_ids: list[str]


class VehicleMatch(DomainModel):
    """Check of the informed make, model and year against the photos."""

    status: VehicleMatchStatus
    reason: str
    evidence_ids: list[str]


class SpecialistFindings(DomainModel):
    """Structured output requested from a specialist agent."""

    vehicle_match: VehicleMatch

    photo_assessments: list[PhotoAssessment]
    damages: list[Damage]
    hypotheses: list[Hypothesis]
    conflicts: list[Conflict]
    evaluated_categories: list[Category]
    limitations: list[str]


class SpecialistReport(DomainModel):
    """Findings attributed to the specialist that produced them."""

    specialist: SpecialistName
    findings: SpecialistFindings


class AgentConclusion(DomainModel):
    """Final position submitted by the orchestrator agent."""

    summary: str
    recommendation: str
    needs_user_input: bool
    questions: list[str]
    follow_up_questions: list[str]
    requires_in_person_inspection: bool
    inspection_reason: str


class CategoryScore(DomainModel):
    """Grade of one category, or the reason it was not evaluated."""

    category: Category
    evaluated: bool
    grade: float | None
    reason: str


class VehicleScore(DomainModel):
    """Score calculated by code from the validated findings."""

    value: int
    band: ScoreBand
    is_partial: bool
    is_provisional: bool = True
    coverage_percent: int
    categories: list[CategoryScore]


class Dossier(DomainModel):
    """Result of an agent run, shown to the user."""

    status: AssessmentStatus
    status_reason: str
    vehicle: VehicleData
    evidence: list[Evidence] = Field(default_factory=list)
    photo_assessments: list[PhotoAssessment] = Field(default_factory=list)
    damages: list[Damage] = Field(default_factory=list)
    hypotheses: list[Hypothesis] = Field(default_factory=list)
    conflicts: list[Conflict] = Field(default_factory=list)
    pending_information: list[str] = Field(default_factory=list)
    questions: list[str] = Field(default_factory=list)
    limitations: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    score: VehicleScore | None = None
    summary: str = ""
    recommendation: str = ""
    requires_human_validation: bool = True
    human_validation_reason: str = ""


class Assessment(DomainModel):
    """Persisted assessment of a vehicle."""

    id: str
    owner: str = Field(exclude=True)
    vehicle: VehicleData
    description: str
    status: AssessmentStatus
    dossier: Dossier | None = None
    error: str | None = None
    created_at: datetime
    updated_at: datetime


class NewEvent(DomainModel):
    """History entry that has not been stored yet."""

    kind: EventKind
    name: str
    input: object | None = None
    output: object | None = None


class AgentEvent(DomainModel):
    """Traceable step, tool call, agent decision or user intervention."""

    run: int
    kind: EventKind
    name: str
    input: object | None = None
    output: object | None = None
    created_at: datetime
    hash: str


class AssessmentProgress(DomainModel):
    """Lightweight view of a run, meant to be polled."""

    id: str
    status: AssessmentStatus
    stage: AssessmentStage
    last_action: str | None
    is_finished: bool
    poll_after_ms: int | None
    error: str | None
    updated_at: datetime


class AssessmentDetails(DomainModel):
    """Assessment together with everything needed to audit it."""

    assessment: Assessment
    events: list[AgentEvent]
    history_intact: bool
    photos: list[Photo]


class AgentRequest(DomainModel):
    """Everything an agent run receives."""

    assessment_id: str
    owner: str
    vehicle: VehicleData
    description: str
    answers: list[str]
    photos: list[Photo]


class PhotoUpload(DomainModel):
    """Raw photo received from the outside world."""

    filename: str
    content: bytes
